"""
CONCEPTBANK (Pei et al., 2026, arXiv:2602.06333) for frozen SAM3 / MedSAM3 on CT,
ported from github.com/pgsmall/ConceptBank (sam3_concept_bank.py) onto the
Thesis A slice pipeline.

  Stage I   target prototype: masked pooling of the frozen image features
            (vision_features) over the GT mask of every positive support slice,
            L2-normalised, averaged into p_c.
  Stage II  representative support mining: keep the top-K support slices by
            cosine similarity to p_c.
  Stage III prototype-consistent concept fusion: score each label-faithful
            candidate prompt by mean Dice on the K slices; softmax(dice / tau)
            over the top-J; fuse their text tokens with ConceptBank's
            fuse_tokens (weighted mean over non-padding positions).

At inference the fused tokens replace the text encoder output (encode_text).

CT adaptations vs the original (documented for the thesis):
  - candidates are scored on full support slices with the same hard-mask
    post-processing used for evaluation, instead of soft probability maps on crops;
  - "lite" mode skips Stages I-II and samples K positive slices at random.
"""

import random
from typing import Dict, List

import numpy as np
import torch
import torch.nn.functional as F

from ct.data import iter_slices, load_case, target_mask
from ct.metrics import dice_iou
from ct.model import TextPromptModel, postprocess

# Label-faithful candidates (rewrites of the MSD Task07 label definitions only:
# label 1 "pancreas", label 2 "pancreatic tumour mass (cyst or tumour)").
# Generated by an LLM (Claude) under the ConceptBank constraint of no new visual concepts,
# and frozen before any scoring.
CANDIDATES = {
    "pancreas": [
        "pancreas", "the pancreas", "pancreatic tissue", "pancreatic parenchyma",
        "pancreas gland", "pancreas organ", "pancreas in abdominal CT",
        "pancreas on CT scan",
    ],
    "tumour": [
        "pancreatic tumour", "pancreatic tumor", "pancreatic cancer", "pancreatic mass",
        "tumor", "pancreatic lesion", "pancreatic cyst or tumour", "pancreatic neoplasm",
        "mass in the pancreas", "pancreatic tumour mass",
    ],
}


def fuse_tokens(selected):
    """ConceptBank fuse_tokens. selected: list of (lf (T,D), pm (T,) bool pad, le (T,D), weight)."""
    T = selected[0][0].shape[0]
    w = torch.tensor([s[3] for s in selected], dtype=torch.float32, device=selected[0][0].device)
    w = w / w.sum().clamp_min(1e-6)
    lf = torch.stack([s[0].float() for s in selected])
    pm = torch.stack([s[1].bool() for s in selected])
    le = torch.stack([s[2].float() for s in selected])
    valid = (~pm).float()
    denom = (w.view(-1, 1) * valid).sum(0)
    pm_f = ~(denom > 1e-6)
    denom = denom.clamp_min(1e-6).view(1, T, 1)
    lf_f = ((w.view(-1, 1, 1) * lf * valid.unsqueeze(-1)).sum(0, keepdim=True) / denom).squeeze(0)
    le_f = ((w.view(-1, 1, 1) * le * valid.unsqueeze(-1)).sum(0, keepdim=True) / denom).squeeze(0)
    return lf_f, pm_f, le_f


def _unpack(text_outputs):
    """forward_text layout -> (lf (T,D), pm (T,), le (T,D)) for a single caption."""
    return (text_outputs["language_features"][:, 0], text_outputs["language_mask"][0],
            text_outputs["language_embeds"][:, 0])


def _pack(lf, pm, le, like):
    return {"language_features": lf.unsqueeze(1).to(like["language_features"].dtype),
            "language_mask": pm.unsqueeze(0),
            "language_embeds": le.unsqueeze(1).to(like["language_embeds"].dtype)}


@torch.no_grad()
def masked_embedding(image_state, gt: np.ndarray) -> torch.Tensor:
    feats = image_state["backbone_out"]["vision_features"][0].float()  # (C, h, w)
    m = torch.from_numpy(gt.astype(np.float32)).to(feats.device)[None, None]
    m = F.interpolate(m, size=feats.shape[-2:], mode="area")[0, 0]
    if m.sum() < 1e-6:  # mask smaller than one feature cell: take the nearest cell
        m = F.interpolate(torch.from_numpy(gt.astype(np.float32))[None, None].to(feats.device),
                          size=feats.shape[-2:], mode="bilinear")[0, 0]
    e = (feats * m).sum((1, 2)) / m.sum().clamp_min(1e-6)
    return e / e.norm().clamp_min(1e-6)


def collect_support(data_dir, cases: List[str], target: str, windowed=True, max_per_case=None, seed=0):
    """List of (case, z, grey, gt) for slices where the target is present."""
    rng = random.Random(seed)
    out = []
    for case in cases:
        img, lbl = load_case(data_dir, case)
        pos = [(case, z, g, target_mask(l, target)) for z, g, l in iter_slices(img, lbl, windowed)
               if target_mask(l, target).any()]
        if max_per_case and len(pos) > max_per_case:
            pos = rng.sample(pos, max_per_case)
        out += pos
    return out


@torch.no_grad()
def build_concept(model: TextPromptModel, support, target: str, mode: str = "full",
                  K: int = 10, J: int = 3, tau: float = 0.05,
                  thr: float = 0.5, nms_iou: float = 0.5, scoring: str = "infer_sam", seed: int = 0) -> Dict:
    """Returns {"text": fused text outputs, "log": diagnostics} for one class."""
    log = {"mode": mode, "K": K, "J": J, "tau": tau, "thr": thr, "nms": nms_iou,
           "scoring": scoring, "n_support_slices": len(support)}
    if mode == "full":
        embs = torch.stack([masked_embedding(model.encode_image(g), gt) for _, _, g, gt in support])
        proto = embs.mean(0)
        proto = proto / proto.norm().clamp_min(1e-6)
        sims = embs @ proto
        idx = torch.topk(sims, k=min(K, len(support))).indices.tolist()
        log["cos_to_proto_all"] = [round(float(s), 4) for s in sims]
    elif mode == "lite":
        idx = random.Random(seed).sample(range(len(support)), min(K, len(support)))
    else:
        raise ValueError(mode)
    chosen = [support[i] for i in idx]
    log["selected"] = [(c, int(z)) for c, z, _, _ in chosen]

    states = [model.encode_image(g) for _, _, g, _ in chosen]
    cand_text = {c: model.encode_text(c) for c in CANDIDATES[target]}
    cand_dice = {}
    for c, t in cand_text.items():
        ds = []
        for st, (_, _, _, gt) in zip(states, chosen):
            pred, _, _ = postprocess(model.ground(st, t), thr, nms_iou, scoring)
            ds.append(dice_iou(pred, gt)[0])
        cand_dice[c] = float(np.mean(ds))
    del states
    ranked = sorted(cand_dice, key=cand_dice.get, reverse=True)
    top = ranked[:max(1, min(J, len(ranked)))]
    s = torch.tensor([cand_dice[c] for c in top])
    w = torch.softmax(s / max(tau, 1e-6), 0).tolist()
    fused = fuse_tokens([(*_unpack(cand_text[c]), wi) for c, wi in zip(top, w)])
    log.update(cand_dice=cand_dice, fused=dict(zip(top, [round(x, 4) for x in w])), top1=ranked[0])
    return {"text": _pack(*fused, cand_text[top[0]]), "top1_text": cand_text[ranked[0]], "log": log}
